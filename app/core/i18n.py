def normalize_language(value: str | UserLanguage | None) -> UserLanguage:
    if isinstance(value, UserLanguage):
        return value
    if isinstance(value, str):
        lowered = value.strip().lower()
        if lowered == UserLanguage.RU.value:
            return UserLanguage.RU
    return DEFAULT_LANGUAGE


def t(language: str | UserLanguage | None, key: str, **kwargs: Any) -> str:
    lang = normalize_language(language).value
    template = TEXTS.get(lang, TEXTS[DEFAULT_LANGUAGE.value]).get(key)
    if template is None:
        template = TEXTS[DEFAULT_LANGUAGE.value][key]
    return template.format(**kwargs)


def category_label(language: str | UserLanguage | None, category: ReportCategory) -> str:
    return t(language, CATEGORY_KEYS[category])


def request_status_label(language: str | UserLanguage | None, status: ClanAccessRequestStatus) -> str:
    return t(language, REQUEST_STATUS_KEYS[status])


def translate_service_error(language: str | UserLanguage | None, exc: Exception) -> str:
    key = SERVICE_ERROR_KEYS.get(str(exc).strip())
    if key is not None:
        return t(language, key)
    return str(exc)


def localize_scheduler_reason(language: str | UserLanguage | None, reason: str) -> str:
    key = SCHEDULER_REASON_KEYS.get(reason.strip())
    if key is not None:
        return t(language, key)
    return reason
